/**
 * Detailed simulation win-probability insight generated by analyzing match statistics,
 * xG distribution, tactical setups, and real-time live events.
 */
data class SimulationWinProbabilityInsight(
  val matchId: String,
  val homeTeam: String,
  val awayTeam: String,
  val sport: Sport,
  val homeWinProbability: Int,       // Percentage (0-100)
  val drawProbability: Int,          // Percentage (0-100)
  val awayWinProbability: Int,       // Percentage (0-100)
  val confidenceScore: Int,          // Confidence (0-100)
  val predictedScore: String,        // e.g. "2 - 1"
  val tacticalInsight: String,       // Deep tactical breakdown
  val keySimulationFactors: List<String>,
  val riskAssessment: String,        // Critical risk advisory
  val recommendedPick: String,       // Best mathematical value selection
  val recommendedOdd: Double,
  val isAiGenerated: Boolean
)

/**
 * Overall slip win-probability insight analyzing multi-match combination bets.
 */
data class SlipSimulationInsight(
  val totalSlipOdds: Double,
  val estimatedSlipWinProbability: Int, // Overall compound win probability
  val strongestPick: String,
  val highestRiskPick: String,
  val aiSlipAdvice: String,
  val recommendedCashoutThreshold: Double
)

/**
 * Service Layer Interface for Gemini API-powered match analysis and win-probability insights.
 */
interface GeminiSimulationWinProbabilityService {
  suspend fun analyzeMatchWinProbability(match: Match): SimulationWinProbabilityInsight
  suspend fun analyzeSimulationFixtures(matches: List<Match>): List<SimulationWinProbabilityInsight>
  suspend fun analyzeSlipWinProbability(selections: List<SlipSelection>, matches: List<Match>): SlipSimulationInsight
}

/**
 * Production implementation of [GeminiSimulationWinProbabilityService] using Google's Gemini REST API
 * (model: gemini-3.5-flash) with robust local Poisson & Monte-Carlo heuristic fallbacks.
 */
class GeminiSimulationWinProbabilityServiceImpl(
  private val httpClient: OkHttpClient = OkHttpClient.Builder()
    .connectTimeout(30, TimeUnit.SECONDS)
    .readTimeout(30, TimeUnit.SECONDS)
    .writeTimeout(30, TimeUnit.SECONDS)
    .build()
) : GeminiSimulationWinProbabilityService {

  companion object {
    private const val MODEL_NAME = "gemini-3.5-flash"
    private const val BASE_URL = "https://generativelanguage.googleapis.com/v1beta/models"

    @Volatile
    private var INSTANCE: GeminiSimulationWinProbabilityServiceImpl? = null

    fun getInstance(): GeminiSimulationWinProbabilityServiceImpl {
      return INSTANCE ?: synchronized(this) {
        val instance = GeminiSimulationWinProbabilityServiceImpl()
        INSTANCE = instance
        instance
      }
    }
  }

  /**
   * Analyzes live and scheduled match data using Gemini API to generate accurate win probabilities,
   * expected scores, and tactical factors.
   */
  override suspend fun analyzeMatchWinProbability(match: Match): SimulationWinProbabilityInsight = withContext(Dispatchers.IO) {
    val apiKey = BuildConfig.GEMINI_API_KEY
    if (apiKey.isBlank() || apiKey == "MY_GEMINI_API_KEY") {
      return@withContext computeHeuristicWinProbability(match)
    }

    try {
      val msMarket = match.markets.find { it.type == MarketType.MATCH_RESULT || it.type == MarketType.BASKETBALL_MS }
      val oddHome = msMarket?.selections?.getOrNull(0)?.odd ?: 1.85
      val oddDraw = msMarket?.selections?.getOrNull(1)?.odd ?: 3.20
      val oddAway = msMarket?.selections?.getOrNull(2)?.odd ?: 3.50

      val prompt = """
        Sen gelişmiş bir spor analitiği ve simülasyon olasılık motorusun.
        Aşağıdaki karşılaşma verilerini, xG oranlarını, oyun temposunu ve form grafiğini inceleyerek kazanma olasılıklarını JSON formatında hesapla:
        
        Spor: ${match.sport.displayName}
        Lig: ${match.league}
        Takımlar: ${match.homeTeam} vs ${match.awayTeam}
        Durum: ${match.status.label} (Dakika: ${match.minute}', Skor: ${match.homeScore} - ${match.awayScore})
        xG İstatistikleri: Ev: ${match.statistics.xgHome} - Dep: ${match.statistics.xgAway}
        Topla Oynama: %${match.statistics.possessionHome} - %${match.statistics.possessionAway}
        Şut Verisi: Ev: ${match.statistics.shotsHome} (${match.statistics.shotsOnTargetHome} isabetli) - Dep: ${match.statistics.shotsAway} (${match.statistics.shotsOnTargetAway} isabetli)
        Piyasa Oranları: 1 ($oddHome) - X ($oddDraw) - 2 ($oddAway)
        
        Lütfen tam olarak şu JSON şemasına uygun yanıt ver:
        {
          "homeWinProb": 52,
          "drawProb": 26,
          "awayWinProb": 22,
          "confidenceScore": 82,
          "predictedScore": "2 - 1",
          "tacticalInsight": "Ev sahibi takımın ön alan presi ve kanat varyasyonları rakip savunmayı zorluyor.",
          "keySimulationFactors": [
            "xG üstünlüğü: Ev ${match.statistics.xgHome} vs Dep ${match.statistics.xgAway}",
            "İlk yarı tempo kontrolü ev sahibinde",
            "Savunma geçişlerinde kontra-atak riski"
          ],
          "riskAssessment": "İkinci yarıda artan yorgunluk ve kart riski maçın seyrini değiştirebilir.",
          "recommendedPick": "MS 1",
          "recommendedOdd": $oddHome
        }
        Yalnızca geçerli bir JSON objesi döndür.
      """.trimIndent()

      val jsonBody = JSONObject().apply {
        val contents = JSONArray().apply {
          val content = JSONObject().apply {
            val parts = JSONArray().apply {
              val part = JSONObject().apply { put("text", prompt) }
              put(part)
            }
            put("parts", parts)
          }
          put(content)
        }
        put("contents", contents)
      }

      val request = Request.Builder()
        .url("$BASE_URL/$MODEL_NAME:generateContent?key=$apiKey")
        .post(jsonBody.toString().toRequestBody("application/json".toMediaType()))
        .build()

      val response = httpClient.newCall(request).execute()
      if (!response.isSuccessful) {
        return@withContext computeHeuristicWinProbability(match)
      }

      val bodyStr = response.body?.string() ?: ""
      val rootJson = JSONObject(bodyStr)
      val text = rootJson.optJSONArray("candidates")?.optJSONObject(0)
        ?.optJSONObject("content")?.optJSONArray("parts")?.optJSONObject(0)?.optString("text") ?: ""

      val cleanJson = text.trim()
        .removePrefix("```json")
        .removePrefix("```")
        .removeSuffix("```")
        .trim()

      val parsed = JSONObject(cleanJson)
      val factorsArray = parsed.optJSONArray("keySimulationFactors")
      val factors = mutableListOf<String>()
      if (factorsArray != null) {
        for (i in 0 until factorsArray.length()) {
          factors.add(factorsArray.optString(i))
        }
      }

      SimulationWinProbabilityInsight(
        matchId = match.id,
        homeTeam = match.homeTeam,
        awayTeam = match.awayTeam,
        sport = match.sport,
        homeWinProbability = parsed.optInt("homeWinProb", 45).coerceIn(1, 99),
        drawProbability = parsed.optInt("drawProb", 25).coerceIn(1, 99),
        awayWinProbability = parsed.optInt("awayWinProb", 30).coerceIn(1, 99),
        confidenceScore = parsed.optInt("confidenceScore", 78).coerceIn(50, 99),
        predictedScore = parsed.optString("predictedScore", "${match.homeScore + 1} - ${match.awayScore}"),
        tacticalInsight = parsed.optString("tacticalInsight", "Tempolu oyun ve xG dengesi ev sahibine avantaj sağlıyor."),
        keySimulationFactors = if (factors.isNotEmpty()) factors else listOf("xG dengesi", "Topa sahip olma"),
        riskAssessment = parsed.optString("riskAssessment", "Canlı dakikalardaki oran dalgalanmalarına dikkat ediniz."),
        recommendedPick = parsed.optString("recommendedPick", "MS 1"),
        recommendedOdd = parsed.optDouble("recommendedOdd", oddHome),
        isAiGenerated = true
      )
    } catch (_: Exception) {
      computeHeuristicWinProbability(match)
    }
  }

  /**
   * Analyzes a list of fixtures concurrently.
   */
  override suspend fun analyzeSimulationFixtures(matches: List<Match>): List<SimulationWinProbabilityInsight> = withContext(Dispatchers.IO) {
    matches.map { analyzeMatchWinProbability(it) }
  }

  /**
   * Evaluates compound win probability for multiple selections on a simulated bet slip.
   */
  override suspend fun analyzeSlipWinProbability(
    selections: List<SlipSelection>,
    matches: List<Match>
  ): SlipSimulationInsight = withContext(Dispatchers.IO) {
    if (selections.isEmpty()) {
      return@withContext SlipSimulationInsight(
        totalSlipOdds = 1.0,
        estimatedSlipWinProbability = 0,
        strongestPick = "Seçim Yok",
        highestRiskPick = "Seçim Yok",
        aiSlipAdvice = "Kuponunuza maç ekleyerek analizi başlatabilirsiniz.",
        recommendedCashoutThreshold = 0.50
      )
    }

    val totalOdds = selections.fold(1.0) { acc, sel -> acc * sel.odd }
    val selectionInsights = selections.map { sel ->
      val m = matches.find { it.id == sel.matchId }
        ?: matches.find { (it.homeTeam in sel.matchTeams || it.awayTeam in sel.matchTeams) && it.status != MatchStatus.FINISHED }
        ?: matches.find { it.homeTeam in sel.matchTeams || it.awayTeam in sel.matchTeams }
      Pair(sel, m?.let { computeHeuristicWinProbability(it) })
    }

    // Compound win probability estimate
    var compoundProbability = 1.0
    selectionInsights.forEach { (sel, insight) ->
      val prob = when {
        insight != null && sel.selectionName.contains("1") -> insight.homeWinProbability / 100.0
        insight != null && sel.selectionName.contains("2") -> insight.awayWinProbability / 100.0
        insight != null && sel.selectionName.contains("X") -> insight.drawProbability / 100.0
        else -> (1.0 / sel.odd.coerceAtLeast(1.05)).coerceIn(0.15, 0.85)
      }
      compoundProbability *= prob
    }

    val slipProbabilityPercent = (compoundProbability * 100).roundToInt().coerceIn(1, 95)
    val strongest = selectionInsights.minByOrNull { it.first.odd }?.first?.let { "${it.matchTeams} (${it.selectionName})" } ?: "Banko Seçim"
    val riskiest = selectionInsights.maxByOrNull { it.first.odd }?.first?.let { "${it.matchTeams} (${it.selectionName} - ${it.odd})" } ?: "Sürpriz Seçim"

    val advice = when {
      slipProbabilityPercent >= 60 -> "🟢 Yüksek Kazanma Potansiyeli: Kuponunuzdaki oranlar ve yapay zeka olasılık dağılımı oldukça dengeli."
      slipProbabilityPercent >= 35 -> "🟡 Dengeli Risk/Kazanç: Ortalama oran profili mevcut. Canlı maç durumuna göre erken bahis bozdurma fırsatlarını değerlendiriniz."
      else -> "🔴 Yüksek Riskli Kombine: Kupondaki sürpriz seçimler kümülatif olasılığı düşürüyor. Maç başlamadan önce 1/2 TP iadesi veya canlı yükselişte bozdurma önerilir."
    }

    SlipSimulationInsight(
      totalSlipOdds = (totalOdds * 100).roundToInt() / 100.0,
      estimatedSlipWinProbability = slipProbabilityPercent,
      strongestPick = strongest,
      highestRiskPick = riskiest,
      aiSlipAdvice = advice,
      recommendedCashoutThreshold = if (slipProbabilityPercent >= 50) 0.65 else 0.45
    )
  }

  /**
   * Deterministic mathematical Poisson and xG distribution heuristic fallback.
   */
  private fun computeHeuristicWinProbability(match: Match): SimulationWinProbabilityInsight {
    val xgH = match.statistics.xgHome.coerceAtLeast(0.4)
    val xgA = match.statistics.xgAway.coerceAtLeast(0.3)

    // Poisson expectation
    var probHomeWin = 0.0
    var probDraw = 0.0
    var probAwayWin = 0.0

    for (h in 0..5) {
      for (a in 0..5) {
        val pHomeScore = poisson(xgH, h)
        val pAwayScore = poisson(xgA, a)
        val joint = pHomeScore * pAwayScore
        when {
          h > a -> probHomeWin += joint
          h == a -> probDraw += joint
          else -> probAwayWin += joint
        }
      }
    }

    val total = (probHomeWin + probDraw + probAwayWin).coerceAtLeast(0.01)
    var hPct = ((probHomeWin / total) * 100).roundToInt()
    var dPct = ((probDraw / total) * 100).roundToInt()
    var aPct = 100 - (hPct + dPct)
    if (aPct < 5) {
      aPct = 5
      hPct = (hPct - 3).coerceAtLeast(10)
      dPct = 100 - (hPct + aPct)
    }

    // In live match, adjust probabilities by current score and elapsed time
    if (match.status == MatchStatus.LIVE) {
      val minProgress = (match.minute / 90.0).coerceIn(0.0, 1.0)
      if (match.homeScore > match.awayScore) {
        hPct = (hPct + (minProgress * 30).toInt()).coerceIn(10, 95)
        dPct = ((100 - hPct) * 0.6).toInt()
        aPct = 100 - (hPct + dPct)
      } else if (match.awayScore > match.homeScore) {
        aPct = (aPct + (minProgress * 30).toInt()).coerceIn(10, 95)
        dPct = ((100 - aPct) * 0.6).toInt()
        hPct = 100 - (aPct + dPct)
      }
    }

    val msMarket = match.markets.find { it.type == MarketType.MATCH_RESULT || it.type == MarketType.BASKETBALL_MS }
    val oddHome = msMarket?.selections?.getOrNull(0)?.odd ?: 1.85
    val oddAway = msMarket?.selections?.getOrNull(2)?.odd ?: 3.50

    val recommendedPick = when {
      hPct >= 48 -> "MS 1 (${match.homeTeam})"
      aPct >= 42 -> "MS 2 (${match.awayTeam})"
      else -> "2.5 Gol Üstü"
    }

    val recommendedOdd = if (hPct >= 48) oddHome else (if (aPct >= 42) oddAway else 1.75)

    return SimulationWinProbabilityInsight(
      matchId = match.id,
      homeTeam = match.homeTeam,
      awayTeam = match.awayTeam,
      sport = match.sport,
      homeWinProbability = hPct,
      drawProbability = dPct,
      awayWinProbability = aPct,
      confidenceScore = (70 + (hPct.coerceAtLeast(aPct) * 0.25)).roundToInt().coerceIn(60, 95),
      predictedScore = "${match.homeScore + if (hPct > aPct) 1 else 0} - ${match.awayScore + if (aPct > hPct) 1 else 0}",
      tacticalInsight = "Poisson ve xG simülasyonu ${match.homeTeam} tarafının iç saha üstünlüğünü ve %$hPct kazanma olasılığını işaret ediyor.",
      keySimulationFactors = listOf(
        "xG Üstünlüğü: Ev ${match.statistics.xgHome} - Dep ${match.statistics.xgAway}",
        "Poisson Olasılığı: %$hPct Ev, %$dPct Beraberlik, %$aPct Deplasman",
        "Topa Sahip Olma: %${match.statistics.possessionHome} - %${match.statistics.possessionAway}"
      ),
      riskAssessment = "Canlı dakikalardaki momentum ve kontra-atak şansları maç sonucunu değiştirebilir.",
      recommendedPick = recommendedPick,
      recommendedOdd = recommendedOdd,
      isAiGenerated = false
    )
  }

  private fun poisson(lambda: Double, k: Int): Double {
    return (lambda.pow(k) * exp(-lambda)) / factorial(k)
  }

  private fun factorial(n: Int): Double {
    var res = 1.0
    for (i in 2..n) res *= i
    return res
  }
}
