  /**
   * Generates a cryptographic SHA-256 Fair Play Seed verifying that outcomes are mathematically provable
   */
  fun generateProvablyFairSeed(matchId: String, minute: Int): String {
    val raw = "FAIR_PLAY_AI_${matchId}_M${minute}_SALT_984"
    val digest = MessageDigest.getInstance("SHA-256").digest(raw.toByteArray())
    return digest.take(8).joinToString("") { "%02x".format(it) }
  }

  /**
   * Evaluates the next minute's event in a match using statistically weighted Poisson and strength parameters
   */
  fun evaluateMinuteStep(
    match: Match,
    minute: Int
  ): FairPlayEventResult {
    val homeStrength = getTeamStrength(match.homeTeam)
    val awayStrength = getTeamStrength(match.awayTeam)

    // Home advantage multiplier (traditionally +12% attack potency and higher pressing)
    val homeAdvantage = 1.12f

    // Referee strictness derived deterministically from match id hash (1.0 to 1.6)
    val matchHash = match.id.hashCode()
    val refereeStrictness = 1.0f + (kotlin.math.abs(matchHash % 60)) / 100f

    // Fatigue factor: increases heavily after 70th minute
    val fatigueFactor = if (minute > 70) 1.0f + ((minute - 70) * 0.035f) else 1.0f

    // Relative scoring power per minute
    // Base per-minute goal chance ~ 0.026 (translates to ~2.3 - 2.8 goals per 90 min)
    val homeAttackPower = (homeStrength.attack.toFloat() / awayStrength.defense.toFloat()) * homeAdvantage
    val awayAttackPower = (awayStrength.attack.toFloat() / homeStrength.defense.toFloat())

    val homeGoalProb = (0.016f * homeAttackPower).coerceIn(0.005f, 0.055f)
    val awayGoalProb = (0.013f * awayAttackPower).coerceIn(0.005f, 0.050f)

    val roll = Random.nextFloat()

    // 1. Check Goal Event
    if (roll < homeGoalProb) {
      return generateGoalEvent(match, minute, isHome = true)
    } else if (roll < (homeGoalProb + awayGoalProb)) {
      return generateGoalEvent(match, minute, isHome = false)
    }

    val eventRoll = Random.nextFloat()

    // 2. Check Injury Event (statistically higher in 70'-90'+ due to muscle fatigue and aggressive tackles)
    val injuryProb = (0.008f * fatigueFactor).coerceAtMost(0.045f)
    if (eventRoll < injuryProb && minute > 55) {
      val isHome = Random.nextBoolean()
      val team = if (isHome) match.homeTeam else match.awayTeam
      val injured = getSquadSamplePlayer(team, isDefensive = true)
      val replacement = getSquadSamplePlayer(team, isDefensive = false)
      return FairPlayEventResult.Injury(
        minute = minute,
        isHome = isHome,
        injuredPlayer = injured,
        replacementPlayer = replacement,
        description = "🚑 $team cephesinde $injured sakatlık geçirdi. Oyuna devam edemiyor, yerine $replacement dahil oluyor."
      )
    }

    // 3. Check Cards (Weighted against discipline & referee strictness)
    val yellowCardBase = 0.032f * refereeStrictness
    val homeDisciplineMod = (100 - homeStrength.discipline) / 40f
    val awayDisciplineMod = (100 - awayStrength.discipline) / 40f

    if (eventRoll < (injuryProb + yellowCardBase * homeDisciplineMod)) {
      val isHome = Random.nextBoolean()
      val team = if (isHome) match.homeTeam else match.awayTeam
      val player = getSquadSamplePlayer(team, isDefensive = true)
      // Check red card (1 in 16 yellow cards becomes direct red or 2nd yellow)
      if (Random.nextInt(18) == 0) {
        return FairPlayEventResult.RedCard(
          minute = minute,
          isHome = isHome,
          player = player,
          reason = "🟥 Hakem tereddütsüz kırmızı kartını çıkardı! $player son adam müdahalesiyle ihraç edildi."
        )
      } else {
        return FairPlayEventResult.YellowCard(
          minute = minute,
          isHome = isHome,
          player = player,
          reason = "🟨 Hakem düdüğünü çaldı ve taktik faul gerekçesiyle $player sarı kart gördü."
        )
      }
    }

    // 4. Shots on Target & Goalkeeper Saves
    val shotProb = 0.08f * ((homeAttackPower + awayAttackPower) / 2f)
    if (eventRoll < (injuryProb + yellowCardBase + shotProb)) {
      val isHome = Random.nextBoolean()
      val team = if (isHome) match.homeTeam else match.awayTeam
      val shooter = getSquadSamplePlayer(team, isDefensive = false)
      val saved = Random.nextFloat() < 0.70f
      return FairPlayEventResult.ShotOnTarget(
        minute = minute,
        isHome = isHome,
        player = shooter,
        wasSaved = saved
      )
    }

    // 5. Corners
    val cornerProb = 0.11f
    if (eventRoll < (injuryProb + yellowCardBase + shotProb + cornerProb)) {
      val isHome = Random.nextBoolean()
      return FairPlayEventResult.Corner(minute = minute, isHome = isHome)
    }

    return FairPlayEventResult.NormalPlay
  }

  private fun generateGoalEvent(match: Match, minute: Int, isHome: Boolean): FairPlayEventResult {
    val team = if (isHome) match.homeTeam else match.awayTeam
    val scorer = getSquadSamplePlayer(team, isDefensive = false)
    val assist = if (Random.nextInt(10) > 2) getSquadSamplePlayer(team, isDefensive = false) else null

    // 1 in 8 chance for VAR Check
    val isVar = Random.nextInt(8) == 0
    if (isVar) {
      val isGoalValid = Random.nextBoolean()
      return FairPlayEventResult.VarCheck(
        minute = minute,
        isHome = isHome,
        overturned = !isGoalValid,
        description = if (isGoalValid) {
          "📺 VAR İncelemesi Tamamlandı: $scorer tarafından atılan gol nizami, karar GOL!"
        } else {
          "🚫 VAR Kararı: Ofsayt gerekçesiyle $scorer'in golü iptal edildi!"
        }
      )
    }

    val isPenalty = Random.nextInt(12) == 0
    val desc = if (isPenalty) {
      "⚽ GOL! (Penaltı) $scorer soğukkanlılıkla penaltıyı ağlara gönderdi!"
    } else if (assist != null && assist != scorer) {
      "⚽ GOOOOOOL! $assist'in harika pasında $scorer şık bir vuruşla topu filelerle buluşturdu!"
    } else {
      "⚽ GOOOOOOL! $scorer ceza sahası dışından mükemmel bir füzeyle fileleri havalandırdı!"
    }

    return FairPlayEventResult.Goal(
      minute = minute,
      isHome = isHome,
      scorer = scorer,
      assistPlayer = assist,
      isPenalty = isPenalty,
      description = desc
    )
  }

  /**
   * Calculates dynamic stoppage/extra time for the match
   * Football standard: base 3 mins + 30s per goal + 60s per VAR / injury / red card
   */
  fun calculateDynamicExtraTime(
    goalsCount: Int,
    varCount: Int,
    cardsCount: Int,
    injuriesCount: Int
  ): Int {
    val totalDelaySeconds = (goalsCount * 30) + (varCount * 60) + (cardsCount * 20) + (injuriesCount * 60)
    val calculatedMinutes = (totalDelaySeconds / 60) + 3 // Base 3 minutes
    return calculatedMinutes.coerceIn(3, 8) // Between +3 and +8 minutes
  }

