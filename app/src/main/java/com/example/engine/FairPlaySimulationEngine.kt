/**
 * Team strength parameters for statistically weighted match outcomes.
 */
data class TeamStrength(
  val attack: Int,      // 50 - 99
  val defense: Int,     // 50 - 99
  val midfield: Int,    // 50 - 99
  val discipline: Int,  // 50 - 99 (Higher = fewer cards/fouls)
  val stamina: Int = 82 // Resistance to late-game fatigue & injuries
)

/**
 * Detailed event generated by the Fair Play Engine
 */
sealed class FairPlayEventResult {
  data class Goal(
    val minute: Int,
    val isHome: Boolean,
    val scorer: String,
    val assistPlayer: String?,
    val isPenalty: Boolean = false,
    val description: String
  ) : FairPlayEventResult()

  data class YellowCard(
    val minute: Int,
    val isHome: Boolean,
    val player: String,
    val reason: String
  ) : FairPlayEventResult()

  data class RedCard(
    val minute: Int,
    val isHome: Boolean,
    val player: String,
    val reason: String
  ) : FairPlayEventResult()

  data class Injury(
    val minute: Int,
    val isHome: Boolean,
    val injuredPlayer: String,
    val replacementPlayer: String,
    val description: String
  ) : FairPlayEventResult()

  data class VarCheck(
    val minute: Int,
    val isHome: Boolean,
    val overturned: Boolean,
    val description: String
  ) : FairPlayEventResult()

  data class ShotOnTarget(
    val minute: Int,
    val isHome: Boolean,
    val player: String,
    val wasSaved: Boolean
  ) : FairPlayEventResult()

  data class Corner(
    val minute: Int,
    val isHome: Boolean
  ) : FairPlayEventResult()

  object NormalPlay : FairPlayEventResult()
}

